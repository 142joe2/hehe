// Report Preview & Export toolbar for Oversight Reports
// Shared across all 14 report sections. Renders the normalized `data.report`
// from the backend builders and provides Print / Export PDF / Export Excel.

let __currentReportKey = "";
let __currentReportParams = "";

// ---------------------------------------------------------------------------
// Toolbar injection
// ---------------------------------------------------------------------------

function attachReportToolbar(contentDivId, report, reportKey, params) {
  if (!report) return;
  const container = document.getElementById(contentDivId);
  if (!container) return;

  const name = report.report_name || report.report_key || "Report";
  const qs = params ? params.toString() : "";
  const xlsxUrl = `/api/president/oversight/export/?report_key=${reportKey}&format=xlsx&${qs}`;
  const pdfUrl = `/api/president/oversight/export/?report_key=${reportKey}&format=pdf&${qs}`;

  const toolbar = document.createElement("div");
  toolbar.className = "report-preview-toolbar";
  toolbar.innerHTML = `
    <div class="rpt-title">
      <i class="fas fa-print"></i>
      <div>
        <strong>${escapeHtml(name)}</strong>
        <span>Print preview &amp; export options</span>
      </div>
    </div>
    <div class="rpt-actions">
      <button type="button" class="rpt-btn rpt-btn-primary" onclick="openReportPreview()">
        <i class="fas fa-eye"></i> Print Preview
      </button>
      <a class="rpt-btn" href="${pdfUrl}" download>
        <i class="fas fa-file-pdf"></i> Export PDF
      </a>
      <a class="rpt-btn" href="${xlsxUrl}" download>
        <i class="fas fa-file-excel"></i> Export Excel
      </a>
    </div>
  `;
  container.prepend(toolbar);
}

// ---------------------------------------------------------------------------
// Print preview modal
// ---------------------------------------------------------------------------

function openReportPreview() {
  // Pull the most recent report data stored by the render functions.
  const source = window.__latestOversightReport;
  if (!source || !source.report) return;

  const report = source.report;
  __currentReportKey = source.reportKey || "";
  __currentReportParams = source.params ? source.params.toString() : "";
  renderReportPreviewModal(report);
}

function renderReportPreviewModal(report) {
  const overlay = document.getElementById("report-preview-overlay");
  if (!overlay) return;

  const name = report.report_name || report.report_key || "Report";
  const qs = __currentReportParams;
  const xlsxUrl = `/api/president/oversight/export/?report_key=${__currentReportKey}&format=xlsx&${qs}`;
  const pdfUrl = `/api/president/oversight/export/?report_key=${__currentReportKey}&format=pdf&${qs}`;

  // Summary strip
  let summaryHtml = "";
  if (report.summary && report.summary.length) {
    summaryHtml = `<div class="rpt-modal-summary">`;
    report.summary.forEach((s) => {
      const val = s.type === "currency" ? "₱" + fmtNum(s.value) : s.value;
      summaryHtml += `
        <div class="rpt-modal-summary-item">
          <span>${escapeHtml(s.label)}</span>
          <strong>${escapeHtml(String(val))}</strong>
        </div>`;
    });
    summaryHtml += `</div>`;
  }

  // Filters
  let filtersHtml = "";
  if (report.filters && report.filters.length) {
    filtersHtml = `<div class="rpt-modal-filters">`;
    report.filters.forEach((f) => {
      filtersHtml += `<span><b>${escapeHtml(f.label)}:</b> ${escapeHtml(String(f.value))}</span>`;
    });
    filtersHtml += `</div>`;
  }

  // Main table
  let tableHtml = buildRptTable(report.columns, report.rows);

  // Sections
  let sectionsHtml = "";
  if (report.sections) {
    report.sections.forEach((sec) => {
      sectionsHtml += `<h4 class="rpt-modal-section-title">${escapeHtml(sec.title || "")}</h4>`;
      sectionsHtml += buildRptTable(sec.columns, sec.rows);
    });
  }

  // Notes
  let notesHtml = "";
  if (report.notes && report.notes.length) {
    notesHtml = `<div class="rpt-modal-notes">`;
    report.notes.forEach((n) => { notesHtml += `<p>${escapeHtml(n)}</p>`; });
    notesHtml += `</div>`;
  }

  document.getElementById("report-preview-modal-title").textContent = name;
  document.getElementById("report-preview-modal-meta").innerHTML =
    `<span><b>Generated By:</b> ${escapeHtml(report.generated_by || "President")}</span>` +
    `<span><b>Generated At:</b> ${escapeHtml(report.generated_at || "")}</span>`;

  const headerTitle = String(name || "REPORT").toUpperCase();
  const generatedBy = report.generated_by || "President";
  const generatedAt = report.generated_at || new Date().toLocaleString();

  const reportBody = `
    <div class="rpt-report-shell">
      <div class="rpt-report-sheet">
        <div class="rpt-sheet-header">
          <div class="rpt-sheet-brand">
            <img src="/static/img/isu_caufa_official.png" alt="ISU CAUFA Logo" class="rpt-logo-image" />
            <div class="rpt-brand-copy">
              <div class="rpt-brand-name">ISU CAUFA</div>
              <div class="rpt-brand-sub">ISABELA STATE UNIVERSITY – CAUAYAN CAMPUS FACULTY ASSOCIATION</div>
            </div>
          </div>
          <div class="rpt-sheet-meta">
            <div>Date Generated: ${escapeHtml(generatedAt)}</div>
            <div>Generated By: ${escapeHtml(generatedBy)}</div>
          </div>
        </div>

        <div class="rpt-sheet-title">${escapeHtml(headerTitle)}</div>

        ${summaryHtml || ""}
        ${tableHtml || ""}
        ${sectionsHtml || ""}
        ${notesHtml || ""}
      </div>
    </div>
  `;

  document.getElementById("report-preview-modal-body").innerHTML = reportBody;

  document.getElementById("rpt-export-pdf").href = pdfUrl;
  document.getElementById("rpt-export-excel").href = xlsxUrl;

  overlay.classList.add("open");
  document.body.style.overflow = "hidden";
}

function closeReportPreview() {
  const overlay = document.getElementById("report-preview-overlay");
  if (!overlay) return;
  overlay.classList.remove("open");
  document.body.style.overflow = "";
}

function printReportPreview() {
  window.print();
}

function buildRptTable(columns, rows) {
  if (!columns || !columns.length) return "";
  let html = `<div class="rpt-modal-table-wrap"><table class="rpt-modal-table">`;
  html += `<thead><tr>`;
  columns.forEach((c) => { html += `<th class="rpt-align-${c.align || "left"}">${escapeHtml(c.label)}</th>`; });
  html += `</tr></thead><tbody>`;
  if (!rows || !rows.length) {
    html += `<tr><td colspan="${columns.length}" class="rpt-empty">No records found</td></tr>`;
  } else {
    rows.forEach((r) => {
      html += `<tr>`;
      columns.forEach((c) => {
        html += `<td class="rpt-align-${c.align || "left"}">${escapeHtml(String(r[c.key] ?? ""))}</td>`;
      });
      html += `</tr>`;
    });
  }
  html += `</tbody></table></div>`;
  return html;
}

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

function escapeHtml(value) {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function fmtNum(value) {
  const n = Number(value);
  if (isNaN(n)) return value;
  return n.toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}